import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'

import { format } from 'prettier'

import { captureProcess } from '../../workspace/infrastructure/process.ts'
import { corpusRoot } from '../../workspace/paths.ts'
import { protocolSchemas } from './comparison.ts'
import type { Schema } from './schema.ts'

const fieldName = (name: string) =>
  (name[0].toUpperCase() + name.slice(1))
    .replace(/Id$/, 'ID')
    .replace(/Sha256$/, 'SHA256')
    .replace(/Ms$/, 'MS')
    .replace(/Us$/, 'US')

export function goProtocolTypes() {
  const definitions = new Map<string, string>()
  const typeName = (schema: Schema): string => {
    switch (schema.kind) {
      case 'string':
        return 'string'
      case 'boolean':
        return 'bool'
      case 'number':
        return schema.integer ? 'int' : 'float64'
      case 'array':
        return '[]' + typeName(schema.items)
      case 'record':
        return 'map[string]' + typeName(schema.values)
      case 'enum':
        definitions.set(schema.name, `type ${schema.name} string`)
        return schema.name
      case 'object': {
        const fields = Object.entries(schema.properties).map(
          ([name, value]) =>
            `\t${fieldName(name)} ${typeName(value)} \`json:"${name}"\``
        )
        definitions.set(
          schema.name,
          `type ${schema.name} struct {\n${fields.join('\n')}\n}`
        )
        return schema.name
      }
    }
  }
  for (const schema of Object.values(protocolSchemas)) typeName(schema)
  return (
    '// Code generated by protocol/generate.ts. DO NOT EDIT.\npackage worker\n\n' +
    [...definitions.values()].join('\n\n') +
    '\n'
  )
}

export const protocolJSON = () =>
  JSON.stringify(protocolSchemas, null, 2) + '\n'

export async function generateProtocol(check = false) {
  const temporary = await mkdtemp(path.join(os.tmpdir(), 'corpus-protocol-'))
  try {
    const source = path.join(temporary, 'protocol.go')
    await writeFile(source, goProtocolTypes())
    const formatted = await captureProcess('gofmt', [source], temporary)
    for (const [file, content] of [
      ['generated_protocol.go', formatted],
      [
        'protocol_schema.json',
        await format(protocolJSON(), {
          parser: 'json',
          printWidth: 80,
          tabWidth: 2,
          endOfLine: 'lf'
        })
      ]
    ] as const) {
      const target = path.join(corpusRoot, 'comparison/go', file)
      if (check) {
        if ((await readFile(target, 'utf8')) !== content)
          throw new Error('Stale corpus protocol: ' + file)
      } else await writeFile(target, content)
    }
  } finally {
    await rm(temporary, { recursive: true, force: true })
  }
}

if (Bun.main === Bun.fileURLToPath(import.meta.url))
  await generateProtocol(Bun.argv.includes('--check'))
